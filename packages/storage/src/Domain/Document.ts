import { Model } from "@effect/sql";
import { Schema } from "effect";
import { AccountId } from "./Account.ts";

export const DocumentStatusType = Schema.Literal(
  "new",
  "classifying",
  "extracting",
  "validating",
  "pending",
  "approved",
  "rejected",
);

export const MimeType = Schema.String.pipe(
  Schema.pattern(
    /^[a-zA-Z0-9]+\/[a-zA-Z0-9\-.+]+(;[a-zA-Z0-9\-.+=]+=[a-zA-Z0-9\-.+=]+)*$/,
  ),
  Schema.annotations({
    title: "MimeType",
    description: "A valid MIME type",
  }),
  Schema.brand("MimeType"),
);
export type MimeType = typeof MimeType.Type;

export const ConfidenceScore = Schema.Number.pipe(
  Schema.between(0, 100),
  Schema.annotations({
    title: "ConfidenceScore",
    description: "Confidence score for document classification (0-100)",
  }),
  Schema.brand("ConfidenceScore"),
);
export type ConfidenceScore = typeof ConfidenceScore.Type;

export const DocumentId = Schema.Number.pipe(Schema.brand("DocumentId"));
export type DocumentId = typeof DocumentId.Type;

export class Document extends Model.Class<Document>("Document")({
  id: Model.GeneratedByApp(DocumentId), // UUIDv7 generated by app
  accountId: AccountId, // Tenant ownership
  receivedAt: Model.DateTimeFromDate,
  fileName: Schema.NonEmptyTrimmedString,
  fileSize: Schema.Number.pipe(Schema.positive()),
  mimeType: MimeType,
  status: DocumentStatusType,
  numberOfPages: Model.FieldOption(Schema.Number.pipe(Schema.positive())),
  documentType: Model.FieldOption(Schema.NonEmptyTrimmedString),
  confidenceScore: Model.FieldOption(ConfidenceScore),
  workflowId: Model.FieldOption(Schema.String), // Trigger.dev workflow ID
  processingError: Model.FieldOption(Schema.String),
  filePath: Schema.NonEmptyTrimmedString, // Supabase Storage path
  createdAt: Model.DateTimeInsert,
  updatedAt: Model.DateTimeUpdate,
}) {}

// Json schemas for API input/output
export const DocumentJsonCreate = Document.jsonCreate;
export const DocumentJsonUpdate = Document.jsonUpdate;
export const DocumentJson = Document.json;
